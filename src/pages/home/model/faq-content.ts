/**
 * Разметка FAQPage для всей главной: 16 образовательных ответов плюс 8 организационных.
 * Собирается из тех же массивов, что и видимый текст, поэтому разойтись с ним не может.
 */
export function faqPageJsonLd(): string {
  const entries = [...GUIDE_TOPICS.flatMap((topic) => topic.items), ...ORDER_FAQ];

  return JSON.stringify({
    "@context": "https://schema.org",
    "@type": "FAQPage",
    mainEntity: entries.map((entry) => ({
      "@type": "Question",
      name: entry.q,
      acceptedAnswer: { "@type": "Answer", text: entry.a },
    })),
    // Тексты редактируются людьми — экранируем «<», иначе он оборвёт <script>.
  }).replace(/</g, "\\u003c");
}
