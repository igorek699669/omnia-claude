/**
 * Публичный адрес сайта.
 *
 * Один и тот же нужен трём вещам: базе для метаданных и sitemap, ссылке возврата после
 * оплаты и ссылкам в письмах. Раньше строчка `process.env.BETTER_AUTH_URL ?? localhost`
 * была скопирована в каждое из этих мест — расходились бы молча.
 *
 * Отдельной переменной под адрес сайта в проекте нет намеренно: BETTER_AUTH_URL уже задана
 * везде, где приложение запускается (см. .env.example и deploy.yml), и заводить вторую с тем
 * же значением — лишний повод им разъехаться.
 *
 * Функция, а не константа: значение читается на сервере в момент вызова. В клиентском
 * бандле этой переменной нет, и константа запеклась бы там как localhost.
 */
export function siteUrl(): string {
  return process.env.BETTER_AUTH_URL ?? "http://localhost:3000";
}
