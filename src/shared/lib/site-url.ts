/**
 * Публичный адрес сайта — база для метаданных и sitemap, ссылка возврата после оплаты и
 * ссылки в письмах. Отдельной переменной под него нет намеренно: BETTER_AUTH_URL уже задана
 * везде, где приложение запускается, и вторая с тем же значением только разъехалась бы.
 *
 * Функция, а не константа: в клиентском бандле переменной нет, и константа запеклась бы
 * там как localhost.
 */
export function siteUrl(): string {
  return process.env.BETTER_AUTH_URL ?? "http://localhost:3000";
}
